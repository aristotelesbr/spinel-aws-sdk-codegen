# frozen_string_literal: true

require 'json'
require_relative 'underscore'
require_relative 'common_errors'

module Codegen
  # The protocol-free part of a generated service: types, errors, stubs, the
  # client and the entry file, from the api-2.json the aws-sdk-ruby gem is
  # generated from. A subclass per protocol writes the serializers and the
  # parsers, and the line that sends a request (#transport). Every operation
  # gets its own code, so nothing walks a model at run time: the output is
  # plain Ruby that Spinel compiles.
  class Service
    GENERATED = '# Generated by spinel-aws-sdk-codegen from aws-sdk-ruby api-2.json. Do not edit.'

    attr_reader :module_name, :api

    # With operation_names, only those operations, the structures they reach
    # and their errors are generated; without, the whole model. A service
    # inside the aws-sdk-core package (STS) loads only the runtime; any other
    # loads aws-sdk-core, as the gem does.
    def initialize(api_path, module_name:, operation_names: nil, in_core: false)
      @api = JSON.parse(File.read(api_path))
      @module_name = module_name
      @shapes = @api['shapes']
      @operation_names = operation_names
      @in_core = in_core
      pagers = File.join(File.dirname(api_path), 'paginators-1.json')
      @paginators = File.exist?(pagers) ? JSON.parse(File.read(pagers))['pagination'] : {}
      unknown = (operation_names || []) - @api['operations'].keys
      raise "not in the model: #{unknown.join(', ')}" unless unknown.empty?
    end

    def metadata = @api['metadata']

    # name => file contents, paths relative to the package root.
    def files(prefix)
      {
        "#{prefix}.rb" => entry_file(prefix),
        "#{prefix}/types.rb" => types_file,
        "#{prefix}/errors.rb" => errors_file,
        "#{prefix}/serializers.rb" => serializers_file,
        "#{prefix}/parsers.rb" => parsers_file,
        "#{prefix}/stubs.rb" => stubs_file,
        "#{prefix}/client.rb" => client_file,
      }
    end

    # Every [shape name, ruby member names in model order] the generator
    # emits, for checking against the gem's own ClientApi.
    def member_names
      structures.to_h { |name, shape| [name, members(shape).map { |m| m[:ruby] }] }
    end

    private

    # ---- model helpers -------------------------------------------------

    def operations
      ops = @api['operations']
      ops = ops.slice(*@operation_names) if @operation_names
      ops.sort.to_h
    end

    def structures
      all = @shapes.select { |_, s| s['type'] == 'structure' }
      return all.sort.to_h unless @operation_names

      roots = operations.values.flat_map { |op| [op.dig('input', 'shape'), op.dig('output', 'shape')] }.compact
      names = reachable_structures(roots.uniq) | errors.keys
      all.slice(*names).sort.to_h
    end

    def shape(name) = @shapes.fetch(name)

    def members(shape)
      (shape['members'] || {}).map do |wire, ref|
        {
          wire: wire,
          ruby: Underscore.underscore(wire),
          shape_name: ref['shape'],
          shape: shape(ref['shape']),
          location_name: ref['locationName'] || wire,
          flattened: ref['flattened'] || shape(ref['shape'])['flattened'],
        }
      end
    end

    def op_method(op_name) = Underscore.underscore(op_name)

    def errors
      all = @shapes.select { |_, s| s['exception'] }
      return all.sort.to_h unless @operation_names

      names = operations.values.flat_map { |op| (op['errors'] || []).map { |e| e['shape'] } }
      all.slice(*names).sort.to_h
    end

    def header(requires = [])
      lines = ['# frozen_string_literal: true', '', GENERATED, '']
      requires.each { |r| lines << "require #{r.inspect}" }
      lines << '' unless requires.empty?
      lines.join("\n") + "\n"
    end

    def wrap(body)
      "module Aws\n  module #{module_name}\n#{body}  end\nend\n"
    end

    def indent(text, n)
      text.lines.map { |l| l.strip.empty? ? "\n" : (' ' * n) + l }.join
    end

    def reachable_structures(roots)
      seen = []
      queue = roots.dup
      until queue.empty?
        name = queue.shift
        next if seen.include?(name)
        seen << name
        members(shape(name)).each do |m|
          target = m[:shape]['type'] == 'list' ? m[:shape]['member']['shape'] : m[:shape_name]
          queue << target if shape(target)['type'] == 'structure'
        end
      end
      seen.sort
    end

    # ---- entry ----------------------------------------------------------

    def entry_file(prefix)
      req = %w[types errors serializers parsers stubs client].map { |f| "#{prefix}/#{f}" }
      header([@in_core ? 'aws-sdk-core/runtime' : 'aws-sdk-core'] + req) +
        "module Aws\n  module #{module_name}\n    API_VERSION = #{metadata['apiVersion'].inspect}\n  end\nend\n"
    end

    # ---- types ----------------------------------------------------------

    def types_file
      classes = structures.map { |name, shape| type_class(name, shape) }.join("\n")
      header + wrap(indent("module Types\n#{indent(classes, 2)}end\n", 4))
    end

    def type_class(name, shape)
      ms = members(shape)
      args = ms.map { |m| "#{m[:ruby]}: nil" }.join(', ')
      assigns = ms.map { |m| "  @#{m[:ruby]} = #{m[:ruby]}\n" }.join
      to_h = ms.map { |m| "  hash[:#{m[:ruby]}] = #{to_h_value(m)} unless @#{m[:ruby]}.nil?\n" }.join
      out = +"class #{name}\n"
      out << "  attr_accessor #{ms.map { |m| ":#{m[:ruby]}" }.join(', ')}\n\n" unless ms.empty?
      out << "  def initialize(#{args})\n#{indent(assigns, 2)}  end\n\n"
      out << "  def to_h\n    hash = {}\n#{indent(to_h, 2)}    hash\n  end\nend\n"
      out
    end

    def to_h_value(m)
      case m[:shape]['type']
      when 'structure' then "@#{m[:ruby]}.to_h"
      when 'list'
        member = shape(m[:shape]['member']['shape'])
        member['type'] == 'structure' ? "@#{m[:ruby]}.map(&:to_h)" : "@#{m[:ruby]}"
      else "@#{m[:ruby]}"
      end
    end

    # ---- errors ---------------------------------------------------------

    def errors_file
      classes = errors.keys.map { |name| "class #{name} < ServiceError\nend\n" }.join("\n")
      aliases = error_code_aliases.map { |name| "class #{name} < ServiceError\nend\n" }.join("\n")
      common = common_error_codes.map { |name| "class #{name} < ServiceError\nend\n" }.join("\n")
      names = errors.keys + error_code_aliases + common_error_codes
      lookup = names.map { |name| "when #{name.inspect} then #{name}.new(context, message, Aws::EmptyStructure.new, constant)\n" }.join
      body = +"module Errors\n"
      body << "  # The service's own base error, so `rescue Aws::#{module_name}::Errors::ServiceError`\n"
      body << "  # catches every error of this service, as in the gem.\n"
      body << "  class ServiceError < Aws::Errors::ServiceError\n  end\n\n"
      body << indent(classes, 2) << "\n"
      unless aliases.empty?
        body << "  # Error codes the model gives a shape of another name. The gem names\n"
        body << "  # the raised class after the code (DynamicErrors), so these exist too.\n"
        body << indent(aliases, 2) << "\n"
      end
      body << "  # Error codes any AWS service may return without its model listing\n"
      body << "  # them; the gem creates their classes when it first sees the code.\n"
      body << indent(common, 2) << "\n"
      body << "  # The class for a code, named as the gem's DynamicErrors#error_class\n"
      body << "  # names it; a code the model does not list gets ServiceError.\n"
      body << "  def self.error(code, context, message)\n"
      body << "    constant = Aws::Runtime.error_constant(code)\n"
      body << "    case constant\n#{indent(lookup, 4)}    else ServiceError.new(context, message, Aws::EmptyStructure.new, constant)\n    end\n  end\n"
      body << "end\n"
      header + wrap(indent(body, 4))
    end

    # The model's error codes that differ from their shape's name.
    def error_code_aliases
      errors.filter_map do |name, shape|
        code = shape.dig('error', 'code')
        code if code && code != name && !errors.key?(code)
      end.uniq.sort
    end

    def common_error_codes
      CommonErrors::ALL - errors.keys - error_code_aliases
    end

    # ---- stubs ----------------------------------------------------------

    def stubs_file
      outputs = operations.filter_map { |_, op| op.dig('output', 'shape') }.uniq
      reachable = reachable_structures(outputs)
      ops = operations.map { |name, op| stub_operation(name, op) }.join("\n")
      defaults = reachable.map { |name| stub_default(name) }.join("\n")
      builders = (reachable.map { |name| stub_from_hash(name) } +
                  structure_lists(reachable).map { |name| stub_from_hash_list(name) }).join("\n")
      body = "module Stubs\n#{indent(ops, 2)}\n#{indent(defaults, 2)}\n#{indent(builders, 2)}end\n"
      header + wrap(indent(body, 4))
    end

    # data = nil gives the gem's default stub (EmptyStub); a Hash fills it.
    def stub_operation(name, op)
      output = op.dig('output', 'shape')
      return "def self.#{op_method(name)}(data)\n  Aws::EmptyStructure.new\nend\n" unless output

      u = Underscore.underscore(output)
      cleared = paging_members(name)
      return "def self.#{op_method(name)}(data)\n  data.nil? ? default_#{u}([]) : from_hash_#{u}(data)\nend\n" if cleared.empty?

      out = +"def self.#{op_method(name)}(data)\n  return from_hash_#{u}(data) unless data.nil?\n\n"
      out << "  stub = default_#{u}([])\n"
      cleared.each { |member, value| out << "  stub.#{member} = #{value}\n" }
      out << "  stub\nend\n"
    end

    # The gem's StubData#remove_paging_tokens: a default stub has no next
    # page, so each top-level output token is nil and more_results false.
    def paging_members(op_name)
      pager = @paginators[op_name]
      return [] if pager.nil?

      tokens = Array(pager['output_token']).map { |path| path.split(/ \|\| | or /).first }
      cleared = tokens.reject { |path| path.include?('.') }.map { |path| [Underscore.underscore(path), 'nil'] }
      more = pager['more_results']
      cleared << [Underscore.underscore(more), 'false'] if more && !more.include?('.')
      cleared
    end

    # As Aws::Stubbing::EmptyStub: a String is its shape's name, a number 0,
    # a boolean false, a timestamp Time.now, a list empty; recursion stops at
    # a shape already on the path.
    def stub_default(name)
      ms = members(shape(name))
      out = +"def self.default_#{Underscore.underscore(name)}(visited)\n"
      out << "  return nil if visited.include?(#{name.inspect})\n\n"
      out << "  path = visited + [#{name.inspect}]\n" if ms.any? { |m| m[:shape]['type'] == 'structure' }
      out << "  Types::#{name}.new(\n"
      out << ms.map { |m| "    #{m[:ruby]}: #{stub_default_value(m)}" }.join(",\n")
      out << "\n  )\nend\n"
    end

    def stub_default_value(m)
      case m[:shape]['type']
      when 'structure' then "default_#{Underscore.underscore(m[:shape_name])}(path)"
      when 'list' then '[]'
      when 'map' then '{}'
      when 'integer', 'long' then '0'
      when 'float', 'double' then '0.0'
      when 'boolean' then 'false'
      when 'timestamp' then 'Time.now'
      when 'string' then m[:shape_name].inspect
      else 'nil'
      end
    end

    def stub_from_hash(name)
      ms = members(shape(name))
      out = +"def self.from_hash_#{Underscore.underscore(name)}(hash)\n"
      out << "  return nil if hash.nil?\n\n"
      out << "  Types::#{name}.new(\n"
      out << ms.map { |m| "    #{m[:ruby]}: #{stub_hash_value(m)}" }.join(",\n")
      out << "\n  )\nend\n"
    end

    # The list shapes of structures that the given structures' members use.
    def structure_lists(structure_names)
      structure_names.flat_map do |name|
        members(shape(name)).select do |m|
          m[:shape]['type'] == 'list' && shape(m[:shape]['member']['shape'])['type'] == 'structure'
        end.map { |m| m[:shape_name] }
      end.uniq.sort
    end

    # A list given as nil stays nil, as in the gem's stub data.
    def stub_from_hash_list(name)
      item = Underscore.underscore(shape(name)['member']['shape'])
      "def self.from_hash_#{Underscore.underscore(name)}(values)\n  return nil if values.nil?\n\n" \
        "  values.map { |item| from_hash_#{item}(item) }\nend\n"
    end

    def stub_hash_value(m)
      fetch = "Aws::Runtime::Query.member(hash, :#{m[:ruby]})"
      case m[:shape]['type']
      when 'structure' then "from_hash_#{Underscore.underscore(m[:shape_name])}(#{fetch})"
      when 'list'
        item = m[:shape]['member']['shape']
        shape(item)['type'] == 'structure' ? "from_hash_#{Underscore.underscore(m[:shape_name])}(#{fetch})" : fetch
      else fetch
      end
    end

    # ---- client ---------------------------------------------------------

    def client_file
      methods = operations.map { |name, op| client_operation(name, op) }.join("\n")
      responses = operations.map { |name, op| response_class(name, op) }.join("\n")
      body = +"class Client < Aws::Runtime::Client\n"
      body << "  ENDPOINT_PREFIX = #{metadata['endpointPrefix'].inspect}\n"
      body << "  SIGNING_NAME = #{(metadata['signingName'] || metadata['endpointPrefix']).inspect}\n"
      body << "  SERVICE_ID = #{(metadata['serviceId'] || metadata['endpointPrefix']).inspect}\n"
      body << client_constants << "\n"
      body << "  def initialize(options = {})\n    super(options, ENDPOINT_PREFIX, SIGNING_NAME, SERVICE_ID)\n  end\n\n"
      inputs = operations.map do |name, op|
        input = op.dig('input', 'shape')
        names = input ? members(shape(input)).map { |m| ":#{m[:ruby]}" }.join(', ') : ''
        "when :#{op_method(name)} then [#{names}]\n"
      end.join
      body << "  # The input member names of an operation, as the gem reads them from\n"
      body << "  # its API model (Client.api.operation(name).input.shape.member_names).\n"
      body << "  def self.input_members(operation)\n    case operation\n#{indent(inputs, 4)}    else []\n    end\n  end\n\n"
      body << indent(methods, 2) << "end\n\n"
      body << "module Responses\n#{indent(responses, 2)}end\n"
      header + wrap(indent(body, 4))
    end

    # Extra Client constants a protocol needs, one "  NAME = value\n" each.
    def client_constants = ''

    def client_operation(name, op)
      m = op_method(name)
      out = +"def #{m}(params = {}, options = {})\n"
      out << "  body = Serializers.#{m}(params)\n"
      out << "  stub = next_stub(:#{m})\n"
      out << "  if stub.nil? && stub_responses?\n    data = Stubs.#{m}(nil)\n"
      out << "  elsif stub && stub.data?\n    data = Stubs.#{m}(stub.data)\n"
      out << "  else\n#{indent(transport(name, op), 4)}  end\n"
      out << "  Responses::#{name}.new(data, request_context(body))\n"
      out << "rescue Aws::Runtime::ErrorResponse => e\n"
      out << "  raise Errors.error(e.code, e.context, e.message)\nend\n"
    end

    # An operation the model marks as unauthenticated (authtype "none", or
    # only smithy.api#noAuth) is sent unsigned, as the gem does.
    def signed?(op)
      return false if op['authtype'] == 'none'

      auth = op['auth']
      !(auth.is_a?(Array) && auth == ['smithy.api#noAuth'])
    end

    def response_class(name, op)
      output = op.dig('output', 'shape')
      readers = output ? members(shape(output)).map { |m| "def #{m[:ruby]} = data.#{m[:ruby]}\n" }.join : ''
      "class #{name} < Seahorse::Client::Response\n#{indent(readers, 2)}end\n"
    end
  end
end
